//programacion imperativa

#include <stdio.h>

int main() {
    int suma = 0;
    
    for (int i = 1; i <= 5; i++) { // Bucle que recorre los números del 1 al 5
        suma += i; // Acumulamos la suma
    }
    
    printf("Suma: %d\n", suma); // Imprimimos el resultado
    
    return 0;
}


//Este código sigue el paradigma porque imperativo una ejecución de instrucciones en orden modificando el estado del programa (la variable suma) paso a paso.



