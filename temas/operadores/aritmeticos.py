"""2. Operadores Aritméticos

Los operadores aritméticos se utilizan para realizar operaciones matemáticas."""

a = 10
b = 3

# Suma
print(a + b)  # Salida: 13

# Resta
print(a - b)  # Salida: 7

# Multiplicación
print(a * b)  # Salida: 30

# División
print(a / b)  # Salida: 3.3333333333333335

# División entera
print(a // b)  # Salida: 3

# Módulo (resto de la división)
print(a % b)  # Salida: 1

# Exponenciación
print(a ** b)  # Salida: 1000
