"""Operadores Unarios

Un operador unario opera sobre un solo operando.(numero o variable)"""

#ejemplo:

# Operador unario de negación
x = 5
y = -x  # Negamos el valor de x
print(y)  # Salida: -5

# Operador unario de negación lógica
a = True
b = not a  # Negamos el valor de a
print(b)  # Salida: False
