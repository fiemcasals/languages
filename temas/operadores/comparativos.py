"""Operadores de Comparación

Se utilizan para comparar dos valores."""

a = 5
b = 10

# Igual a
print(a == b)  # Salida: False

# Distinto de
print(a != b)  # Salida: True

# Mayor que
print(a > b)  # Salida: False

# Menor que
print(a < b)  # Salida: True

# Mayor o igual que
print(a >= b)  # Salida: False

# Menor o igual que
print(a <= b)  # Salida: True
