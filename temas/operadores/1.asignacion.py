"""Operadores de Asignación

Se utilizan para asignar valores a variables."""

x = 5  # Asignación simple
x += 3  # x = x + 3  -> x ahora es 8
print(x)  # Salida: 8

x -= 2  # x = x - 2  -> x ahora es 6
print(x)  # Salida: 6

x *= 4  # x = x * 4  -> x ahora es 24
print(x)  # Salida: 24

x /= 6  # x = x / 6  -> x ahora es 4.0
print(x)  # Salida: 4.0

x //= 2  # x = x // 2  -> x ahora es 2.0
print(x)  # Salida: 2.0

x %= 2  # x = x % 2  -> x ahora es 0.0
print(x)  # Salida: 0.0

x **= 3  # x = x ** 3  -> x ahora es 0.0
print(x)  # Salida: 0.0

b = 2

b **= 3 # b*b*b -> b^3
print(b)
